// Writes the compiled Dybbo ABI into the frontend, so the app always calls the contract as built.
//   cd contracts && forge build && node script/export-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";

const art = JSON.parse(readFileSync(new URL("../out/Dybbo.sol/Dybbo.json", import.meta.url)));
const out = new URL("../../web/lib/dybbo/abi.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by contracts/script/export-abi.mjs from the compiled Dybbo contract. Do not edit.\n` +
    `export const dybboAbi = ${JSON.stringify(art.abi, null, 2)} as const;\n`,
);
console.log(`wrote ${art.abi.length} ABI entries`);
